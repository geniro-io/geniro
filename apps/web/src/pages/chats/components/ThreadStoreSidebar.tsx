import { Braces, Clock, Hash, Loader2, RefreshCw, X } from 'lucide-react';
import { Fragment, useCallback, useEffect, useRef, useState } from 'react';

import { threadStoreApi } from '../../../api';
import type {
  NamespaceSummaryDto,
  ThreadStoreEntryDto,
} from '../../../autogenerated';
import { Badge } from '../../../components/ui/badge';
import { Button } from '../../../components/ui/button';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from '../../../components/ui/dialog';
import { JsonViewer } from '../../../components/ui/json-view';
import { ScrollArea } from '../../../components/ui/scroll-area';
import {
  Tooltip,
  TooltipContent,
  TooltipTrigger,
} from '../../../components/ui/tooltip';
import { useWebSocketEvent } from '../../../hooks/useWebSocket';
import type { ThreadStoreUpdateNotification } from '../../../services/WebSocketTypes';
import {
  formatTimestamp,
  MODE_EXPLANATION,
  parseAppendKey,
} from './threadStoreUtils';

interface ThreadStoreSidebarProps {
  open: boolean;
  onClose: () => void;
  /** Internal DB thread id (UUID). Required for REST calls. */
  threadId: string;
  /**
   * External thread id (graphId:subId). Used to filter websocket events,
   * which are scoped to the external id.
   */
  externalThreadId?: string;
}

export const ThreadStoreSidebar = ({
  open,
  onClose,
  threadId,
  externalThreadId,
}: ThreadStoreSidebarProps) => {
  const [namespaces, setNamespaces] = useState<NamespaceSummaryDto[]>([]);
  const [activeNamespace, setActiveNamespace] = useState<string | null>(null);
  const [entries, setEntries] = useState<ThreadStoreEntryDto[]>([]);
  const [loadingNamespaces, setLoadingNamespaces] = useState(false);
  const [loadingEntries, setLoadingEntries] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const nsAbortRef = useRef<AbortController | null>(null);
  const entryAbortRef = useRef<AbortController | null>(null);

  useEffect(
    () => () => {
      nsAbortRef.current?.abort();
      entryAbortRef.current?.abort();
    },
    [],
  );

  const fetchNamespaces = useCallback(async () => {
    nsAbortRef.current?.abort();
    nsAbortRef.current = new AbortController();
    const signal = nsAbortRef.current.signal;
    const capturedThreadId = threadId;

    setLoadingNamespaces(true);
    setError(null);
    try {
      const response = await threadStoreApi.listNamespaces(capturedThreadId, {
        signal,
      });
      if (capturedThreadId !== threadId) {
        return;
      }
      const data = response.data;
      setNamespaces(data);
      setActiveNamespace((prev) => {
        if (data.length > 0 && !data.some((n) => n.namespace === prev)) {
          return data[0]!.namespace;
        }
        if (data.length === 0) {
          return null;
        }
        return prev;
      });
    } catch (err) {
      if (err instanceof Error && err.name === 'CanceledError') {
        return;
      }
      setError(
        err instanceof Error ? err.message : 'Failed to load namespaces',
      );
    } finally {
      if (nsAbortRef.current?.signal === signal) {
        setLoadingNamespaces(false);
      }
    }
  }, [threadId]);

  const fetchEntries = useCallback(
    async (namespace: string) => {
      entryAbortRef.current?.abort();
      entryAbortRef.current = new AbortController();
      const signal = entryAbortRef.current.signal;
      const capturedThreadId = threadId;

      setLoadingEntries(true);
      try {
        const response = await threadStoreApi.listEntries(
          capturedThreadId,
          namespace,
          100,
          undefined,
          { signal },
        );
        if (capturedThreadId !== threadId) {
          return;
        }
        setEntries(response.data);
      } catch (err) {
        if (err instanceof Error && err.name === 'CanceledError') {
          return;
        }
        setError(err instanceof Error ? err.message : 'Failed to load entries');
      } finally {
        if (entryAbortRef.current?.signal === signal) {
          setLoadingEntries(false);
        }
      }
    },
    [threadId],
  );

  useEffect(() => {
    setEntries([]);
  }, [activeNamespace]);

  useEffect(() => {
    if (namespaces.length === 0) {
      setEntries([]);
    }
  }, [namespaces]);

  useEffect(() => {
    if (!open) {
      return;
    }
    void fetchNamespaces();
  }, [open, fetchNamespaces]);

  useEffect(() => {
    if (!open || !activeNamespace) {
      return;
    }
    void fetchEntries(activeNamespace);
  }, [open, activeNamespace, fetchEntries]);

  useWebSocketEvent('thread.store.update', (event) => {
    const notification = event as ThreadStoreUpdateNotification;
    const eventExternalId = notification.threadId;

    const matchesExternal =
      externalThreadId && eventExternalId === externalThreadId;

    if (!matchesExternal) {
      return;
    }

    if (!open) {
      return;
    }

    void fetchNamespaces();
    if (notification.data.namespace === activeNamespace) {
      void fetchEntries(notification.data.namespace);
    }
  });

  const handleRefresh = useCallback(() => {
    void fetchNamespaces();
    if (activeNamespace) {
      void fetchEntries(activeNamespace);
    }
  }, [fetchNamespaces, fetchEntries, activeNamespace]);

  // Single shared dialog — avoids mounting one Dialog per card.
  const [viewedEntry, setViewedEntry] = useState<ThreadStoreEntryDto | null>(
    null,
  );

  if (!open) {
    return null;
  }

  const showLoading = loadingNamespaces && namespaces.length === 0;
  const refreshing = loadingNamespaces || loadingEntries;

  return (
    <>
      <div className="w-72 shrink-0 border-l border-border flex flex-col bg-background overflow-hidden">
        {/* Header */}
        <div className="px-4 py-4 border-b border-border flex justify-between items-center shrink-0">
          <h3 className="text-base font-semibold">Thread store</h3>
          <div className="flex items-center gap-1">
            <Tooltip>
              <TooltipTrigger asChild>
                <Button
                  variant="ghost"
                  size="icon"
                  className="h-7 w-7"
                  onClick={handleRefresh}
                  disabled={refreshing}>
                  {refreshing ? (
                    <Loader2 className="h-3.5 w-3.5 animate-spin" />
                  ) : (
                    <RefreshCw className="h-3.5 w-3.5" />
                  )}
                </Button>
              </TooltipTrigger>
              <TooltipContent>Refresh store</TooltipContent>
            </Tooltip>
            <Tooltip>
              <TooltipTrigger asChild>
                <Button
                  variant="ghost"
                  size="icon"
                  className="h-7 w-7"
                  onClick={onClose}>
                  <X className="h-3.5 w-3.5" />
                </Button>
              </TooltipTrigger>
              <TooltipContent>Close</TooltipContent>
            </Tooltip>
          </div>
        </div>

        {/* Content */}
        <div className="flex-1 min-h-0 overflow-y-auto px-3 py-3 space-y-3">
          {error ? <p className="text-sm text-destructive">{error}</p> : null}

          {showLoading ? (
            <div className="flex justify-center items-center pt-12">
              <Loader2 className="h-5 w-5 animate-spin text-muted-foreground" />
            </div>
          ) : null}

          {!showLoading && namespaces.length === 0 && !error ? (
            <div className="flex flex-col items-center justify-center py-12 text-center">
              <p className="text-sm text-muted-foreground">
                No entries yet. Agents can write here via the Thread Store tools
                (put, append).
              </p>
            </div>
          ) : null}

          {namespaces.length > 0 ? (
            <div className="flex items-center gap-2 flex-wrap">
              {namespaces.map((ns) => (
                <Button
                  key={ns.namespace}
                  type="button"
                  size="sm"
                  variant={
                    ns.namespace === activeNamespace ? 'default' : 'outline'
                  }
                  onClick={() => setActiveNamespace(ns.namespace)}>
                  {ns.namespace}
                  <Badge variant="secondary" className="ml-2">
                    {ns.entryCount}
                  </Badge>
                </Button>
              ))}
            </div>
          ) : null}

          {activeNamespace ? <NamespaceModeHint entries={entries} /> : null}

          {activeNamespace ? (
            <ScrollArea className="max-h-[calc(100vh-260px)]">
              {loadingEntries && entries.length === 0 ? (
                <div className="flex items-center justify-center py-6">
                  <Loader2 className="h-4 w-4 animate-spin text-muted-foreground" />
                </div>
              ) : entries.length === 0 ? (
                <p className="text-sm text-muted-foreground">
                  This namespace is empty.
                </p>
              ) : (
                <ul className="space-y-2">
                  {entries.map((entry) => (
                    <EntryCard
                      key={entry.id}
                      entry={entry}
                      onView={setViewedEntry}
                    />
                  ))}
                </ul>
              )}
            </ScrollArea>
          ) : null}
        </div>
      </div>
      <ValueDialog entry={viewedEntry} onClose={() => setViewedEntry(null)} />
    </>
  );
};

const APPEND_DATE_FMT = new Intl.DateTimeFormat(undefined, {
  month: 'short',
  day: 'numeric',
  hour: 'numeric',
  minute: '2-digit',
  second: '2-digit',
});

const EntryCard = ({
  entry,
  onView,
}: {
  entry: ThreadStoreEntryDto;
  onView: (entry: ThreadStoreEntryDto) => void;
}) => {
  const parsed = entry.mode === 'append' ? parseAppendKey(entry.key) : null;
  const isAppend = entry.mode === 'append';
  const modeLabel = isAppend ? 'append' : 'kv';
  const modeExplain = MODE_EXPLANATION[modeLabel];

  return (
    <li className="rounded-md border border-border bg-card p-3 space-y-2">
      {/* Header — uniform shape: icon + prominent identifier + mode badge */}
      <div className="flex items-start justify-between gap-2">
        <div className="flex items-center gap-1.5 min-w-0 flex-1">
          {parsed ? (
            <Clock className="h-3.5 w-3.5 text-muted-foreground shrink-0" />
          ) : (
            <Hash className="h-3.5 w-3.5 text-muted-foreground shrink-0" />
          )}
          {parsed ? (
            <Tooltip>
              <TooltipTrigger asChild>
                <span className="text-sm font-medium text-foreground truncate cursor-default">
                  {APPEND_DATE_FMT.format(parsed.date)}
                </span>
              </TooltipTrigger>
              <TooltipContent className="font-mono text-xs">
                {entry.key}
              </TooltipContent>
            </Tooltip>
          ) : (
            <span className="text-sm font-mono font-medium text-foreground break-all">
              {entry.key}
            </span>
          )}
        </div>
        <Tooltip>
          <TooltipTrigger asChild>
            <Badge
              variant={isAppend ? 'secondary' : 'outline'}
              className="shrink-0 cursor-help">
              {modeLabel}
            </Badge>
          </TooltipTrigger>
          <TooltipContent className="max-w-xs">{modeExplain}</TooltipContent>
        </Tooltip>
      </div>

      {/* Meta — author, plus updatedAt only for kv (append already shows
          the create-time in the header — append rows are immutable, so
          updatedAt would just duplicate it). */}
      {entry.authorAgentId || !isAppend ? (
        <div className="flex items-baseline gap-x-2 gap-y-0.5 flex-wrap text-[11px] text-muted-foreground">
          {entry.authorAgentId ? (
            <span className="font-medium text-foreground/70">
              {entry.authorAgentId}
            </span>
          ) : null}
          {isAppend ? null : <span>{formatTimestamp(entry.updatedAt)}</span>}
        </div>
      ) : null}

      {/* Tags */}
      {entry.tags && entry.tags.length > 0 ? (
        <div className="flex items-center gap-1 flex-wrap">
          {entry.tags.map((tag) => (
            <Badge key={tag} variant="secondary" className="text-[10px]">
              {tag}
            </Badge>
          ))}
        </div>
      ) : null}

      {/* Value preview — click to open full JSON dialog */}
      <ValuePreview
        value={entry.value as unknown}
        onView={() => onView(entry)}
      />
    </li>
  );
};

const PREVIEW_FIELD_LIMIT = 3;
const PREVIEW_VALUE_CHAR_LIMIT = 60;

const previewScalar = (v: unknown): string => {
  if (v === null) {
    return 'null';
  }
  if (typeof v === 'string') {
    const trimmed =
      v.length > PREVIEW_VALUE_CHAR_LIMIT
        ? `${v.slice(0, PREVIEW_VALUE_CHAR_LIMIT)}…`
        : v;
    return `"${trimmed}"`;
  }
  if (typeof v === 'number' || typeof v === 'boolean') {
    return String(v);
  }
  if (Array.isArray(v)) {
    return `[${v.length} items]`;
  }
  if (typeof v === 'object') {
    return `{${Object.keys(v as object).length} keys}`;
  }
  return String(v);
};

const ValuePreview = ({
  value,
  onView,
}: {
  value: unknown;
  onView: () => void;
}) => {
  // Decide what the preview body looks like based on the value's shape.
  // `min-w-0` / grid `minmax(0, 1fr)` everywhere is load-bearing: without
  // them, a long single-token value (e.g. "repository overview research
  // only") prevents inner spans from shrinking and pushes the whole
  // w-72 sidebar wider than its declared width.
  let body: React.ReactNode;
  if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
    const entries = Object.entries(value as Record<string, unknown>);
    const shown = entries.slice(0, PREVIEW_FIELD_LIMIT);
    const remaining = entries.length - shown.length;
    body = (
      // grid-cols-[auto_minmax(0,1fr)] is the trick: minmax(0, 1fr) lets the
      // value column shrink below its content min-width so `truncate` fires.
      // `flex` + `min-w-0` is less reliable in nested layouts.
      <div className="grid grid-cols-[auto_minmax(0,1fr)] gap-x-1.5 gap-y-0.5 items-baseline">
        {shown.map(([k, v]) => (
          <Fragment key={k}>
            <span className="font-semibold text-foreground/80">{k}:</span>
            <span className="text-foreground/70 truncate">
              {previewScalar(v)}
            </span>
          </Fragment>
        ))}
        {remaining > 0 ? (
          <div className="col-span-2 text-muted-foreground/70 italic">
            +{remaining} more {remaining === 1 ? 'field' : 'fields'}
          </div>
        ) : null}
      </div>
    );
  } else if (Array.isArray(value)) {
    body = (
      <div className="text-foreground/70 italic truncate">
        Array · {value.length} {value.length === 1 ? 'item' : 'items'}
      </div>
    );
  } else if (typeof value === 'string') {
    const display =
      value.length > PREVIEW_VALUE_CHAR_LIMIT * 2
        ? `${value.slice(0, PREVIEW_VALUE_CHAR_LIMIT * 2)}…`
        : value;
    body = (
      <div className="text-foreground/80 line-clamp-2 break-words">
        {display}
      </div>
    );
  } else {
    body = (
      <div className="text-foreground/80 font-mono truncate">
        {previewScalar(value)}
      </div>
    );
  }

  return (
    // `min-w-0 overflow-hidden` on the button is the final safety net: it
    // stops any stray child width from breaching the sidebar's `w-72`.
    <button
      type="button"
      onClick={onView}
      className="w-full min-w-0 overflow-hidden text-left rounded bg-muted/40 hover:bg-muted/60 transition-colors p-2 text-xs font-mono cursor-pointer group">
      {body}
      <div className="mt-1.5 flex items-center gap-1 text-[10px] text-muted-foreground/70 group-hover:text-muted-foreground">
        <Braces className="h-3 w-3" />
        Click to view full JSON
      </div>
    </button>
  );
};

const ValueDialog = ({
  entry,
  onClose,
}: {
  entry: ThreadStoreEntryDto | null;
  onClose: () => void;
}) => {
  const value = entry?.value as unknown;
  // JsonViewer requires `object`; wrap primitives so the viewer still
  // renders them.
  const wrapped: object =
    value !== null && typeof value === 'object' ? value : { value };
  const parsed = entry ? parseAppendKey(entry.key) : null;
  const title = entry
    ? parsed
      ? APPEND_DATE_FMT.format(parsed.date)
      : entry.key
    : '';

  return (
    <Dialog open={!!entry} onOpenChange={(o) => !o && onClose()}>
      <DialogContent className="sm:max-w-[720px] max-h-[80vh] flex flex-col">
        <DialogHeader>
          <DialogTitle className="font-mono break-all">{title}</DialogTitle>
          <DialogDescription className="sr-only">
            Full JSON value for the selected thread store entry.
          </DialogDescription>
        </DialogHeader>
        {entry ? (
          <div className="flex-1 min-h-0 overflow-auto rounded border border-border bg-background p-3">
            <JsonViewer value={wrapped} collapsed={2} />
          </div>
        ) : null}
      </DialogContent>
    </Dialog>
  );
};

const NamespaceModeHint = ({ entries }: { entries: ThreadStoreEntryDto[] }) => {
  if (entries.length === 0) {
    return null;
  }
  const hasAppend = entries.some((e) => e.mode === 'append');
  const hasKv = entries.some((e) => e.mode === 'kv');

  // Pure single-mode namespace: show the matching explanation.
  if (hasAppend && !hasKv) {
    return (
      <div className="flex items-start gap-2 rounded-md border border-border bg-muted/30 px-2.5 py-2 text-xs text-muted-foreground">
        <Clock className="h-3.5 w-3.5 mt-0.5 shrink-0" />
        <span>{MODE_EXPLANATION.append}</span>
      </div>
    );
  }
  if (hasKv && !hasAppend) {
    return (
      <div className="flex items-start gap-2 rounded-md border border-border bg-muted/30 px-2.5 py-2 text-xs text-muted-foreground">
        <Hash className="h-3.5 w-3.5 mt-0.5 shrink-0" />
        <span>{MODE_EXPLANATION.kv}</span>
      </div>
    );
  }

  // Mixed (rare). Don't pretend it's one or the other.
  return (
    <div className="rounded-md border border-border bg-muted/30 px-2.5 py-2 text-xs text-muted-foreground">
      Mixed namespace — contains both append-log and key-value entries. Hover
      the badge on each card to see the difference.
    </div>
  );
};
