// ── accumulatePreparedStatistics — Change 1 regression guard ─────────────────
//
// These scenarios verify that tool items do NOT double-count price/tokens that
// are already contributed by their sibling chat item (which carries the same
// requestTokenUsage reference from the parent AI message DTO).

describe('accumulatePreparedStatistics', () => {
  // Minimal required fields for a ThreadMessageDto used as a chat item's message.
  const makeMinimalDto = (
    id: string,
    requestTokenUsage?: ThreadMessageDto['requestTokenUsage'],
  ): ThreadMessageDto => ({
    id,
    threadId: 'thread-1',
    nodeId: 'node-1',
    externalThreadId: '',
    createdAt: '2024-01-01T00:00:00.000Z',
    updatedAt: '2024-01-01T00:00:00.000Z',
    requestTokenUsage,
    message: {
      id,
      role: 'ai',
      content: 'hello',
    } as ThreadMessageDto['message'],
  });

  it('1.1 — chat + 2 tool siblings sharing requestTokenUsage: totalPrice and totalTokens counted once', () => {
    // Regression guard for the (N+1)x double-count: a single AI turn produces
    // one chat PreparedMessage and N tool PreparedMessages, all carrying the
    // same requestTokenUsage. Only the chat item must contribute to
    // totalPrice/totalTokens; tool items contribute only durationMs + count.
    const sharedUsage: ThreadMessageDto['requestTokenUsage'] = {
      inputTokens: 600,
      outputTokens: 400,
      totalTokens: 1000,
      totalPrice: 0.05,
    };

    const chatItem: PreparedMessage = {
      type: 'chat',
      id: 'chat-1',
      message: makeMinimalDto('chat-1', sharedUsage),
    };

    const toolItem1: PreparedMessage = {
      type: 'tool',
      id: 'tool-1',
      name: 'search',
      status: 'executed',
      requestTokenUsage: sharedUsage,
    };

    const toolItem2: PreparedMessage = {
      type: 'tool',
      id: 'tool-2',
      name: 'fetch',
      status: 'executed',
      requestTokenUsage: sharedUsage,
    };

    const stats = _accumulatePreparedStatistics([
      chatItem,
      toolItem1,
      toolItem2,
    ]);

    expect(stats).toBeDefined();
    // totalPrice and totalTokens must come from the chat item only — NOT tripled.
    expect(stats!.usage!.totalPrice).toBe(0.05);
    expect(stats!.usage!.totalTokens).toBe(1000);
  });

  it('1.2 — 3 tool items with no requestTokenUsage and no sibling chat: accumulator returns undefined', () => {
    // Per-block durationMs aggregates were removed in favour of the live
    // thread-runtime timer (which counts wall-clock once instead of summing
    // per-leaf, fixing the parallel-subagent double-count bug). Tools that
    // carry only a per-leaf durationMs and no requestTokenUsage therefore
    // contribute nothing to the block-level accumulator; with no usage on
    // any item the accumulator reports undefined (count = 0).
    const toolA: PreparedMessage = {
      type: 'tool',
      id: 'tool-a',
      name: 'shell',
      status: 'executed',
      durationMs: 100,
    };

    const toolB: PreparedMessage = {
      type: 'tool',
      id: 'tool-b',
      name: 'shell',
      status: 'executed',
      durationMs: 200,
    };

    const toolC: PreparedMessage = {
      type: 'tool',
      id: 'tool-c',
      name: 'shell',
      status: 'executed',
      durationMs: 300,
    };

    const stats = _accumulatePreparedStatistics([toolA, toolB, toolC]);

    expect(stats).toBeUndefined();
  });

  it('1.3 — communication child block + 2 outer chat items: totalPrice accumulates from both sources', () => {
    // A communication/subagent block contributes its pre-computed statistics as
    // a single item to the parent accumulator; outer chat items contribute their
    // own requestTokenUsage. Together they must sum correctly.
    const chatItem1: PreparedMessage = {
      type: 'chat',
      id: 'outer-chat-1',
      message: makeMinimalDto('outer-chat-1', {
        inputTokens: 100,
        outputTokens: 100,
        totalTokens: 200,
        totalPrice: 0.02,
      }),
    };

    const chatItem2: PreparedMessage = {
      type: 'chat',
      id: 'outer-chat-2',
      message: makeMinimalDto('outer-chat-2', {
        inputTokens: 100,
        outputTokens: 100,
        totalTokens: 200,
        totalPrice: 0.02,
      }),
    };

    const communicationBlock: PreparedMessage = {
      type: 'communication',
      id: 'comm-1',
      toolCallId: 'tc-comm-1',
      innerMessages: [],
      status: 'executed',
      statistics: {
        usage: {
          totalPrice: 0.1,
          totalTokens: 500,
        },
      },
    };

    const stats = _accumulatePreparedStatistics([
      chatItem1,
      communicationBlock,
      chatItem2,
    ]);

    expect(stats).toBeDefined();
    // outer chat 1 ($0.02) + communication block ($0.10) + outer chat 2 ($0.02) = $0.14
    expect(stats!.usage!.totalPrice).toBeCloseTo(0.14, 10);
    expect(stats!.usage!.totalTokens).toBe(900); // 200 + 500 + 200
  });

  it('1.4 — unpriced subagent (totalTokens > 0, totalPrice sums to exactly 0): preserves 0 so formatUsd renders "$0.000"', () => {
    // Primary H2 scenario: subagent ran against an unpriced model, so each
    // request's totalPrice is 0 but totalTokens are populated. The accumulator
    // must preserve `totalPrice === 0` (not coerce to undefined), because the
    // downstream `formatUsd` distinguishes `0 → "$0.000"` from `undefined → "$—"`.
    const chatItem1: PreparedMessage = {
      type: 'chat',
      id: 'chat-unpriced-1',
      message: makeMinimalDto('chat-unpriced-1', {
        inputTokens: 100,
        outputTokens: 50,
        totalTokens: 150,
        totalPrice: 0,
      }),
    };

    const chatItem2: PreparedMessage = {
      type: 'chat',
      id: 'chat-unpriced-2',
      message: makeMinimalDto('chat-unpriced-2', {
        inputTokens: 200,
        outputTokens: 100,
        totalTokens: 300,
        totalPrice: 0,
      }),
    };

    const stats = _accumulatePreparedStatistics([chatItem1, chatItem2]);

    expect(stats).toBeDefined();
    // Tokens are summed normally.
    expect(stats!.usage!.totalTokens).toBe(450);
    // Price is genuine 0 — must NOT be coerced to undefined.
    expect(stats!.usage!.totalPrice).toBe(0);
    // Safety: confirm it's a number, not undefined. `formatUsd(0) === "$0.000"`,
    // `formatUsd(undefined) === "$—"` — we want the "$0.000" path.
    expect(typeof stats!.usage!.totalPrice).toBe('number');
  });

  it('1.5 — in-flight subagent: inner AI msg with tool_calls only credits requestTokenUsage to live SubagentBlock statistics', () => {
    // Regression guard for "live cost shows $0.000" bug: an inner subagent AI
    // message that emits ONLY tool_calls (blank text content) used to lose its
    // requestTokenUsage entirely.  prepareReadyMessages does not push a 'chat'
    // prepared item for blank-content AI messages, and the old one-pass
    // accumulator skipped price/tokens on tool items "because the sibling chat
    // carries it" — but with no sibling, the cost was dropped.  The two-pass
    // walk now credits via the tool branch when no chat/reasoning sibling has
    // already credited the same requestTokenUsage object.
    const parentToolCallId = 'tc-running-sub-15';
    const innerToolCallId = 'inner-tc-shell-15';

    const parentAiCall = makeSubagentCallMsg('parent-ai-15', parentToolCallId);

    // Inner AI message: blank content + tool_calls, with usage info.
    // Using cast to ThreadMessageDto['message'] to satisfy the auto-generated type.
    const innerAi = (() => {
      const msg = makeMsg('inner-ai-15', 'ai', '', {
        __toolCallId: parentToolCallId,
        __subagentCommunication: true,
      });
      msg.requestTokenUsage = {
        inputTokens: 200,
        outputTokens: 50,
        totalTokens: 250,
        totalPrice: 0.01,
      };
      // Manually add toolCalls to the message object.
      (msg.message as unknown as Record<string, unknown>).toolCalls = [
        { id: innerToolCallId, name: 'shell' },
      ];
      return msg;
    })();

    // Inner tool result message.
    const innerToolResult = (() => {
      const msg = makeMsg('inner-tool-15', 'tool', 'ok', {
        __toolCallId: parentToolCallId,
        __subagentCommunication: true,
      });
      (msg.message as unknown as Record<string, unknown>).name = 'shell';
      (msg.message as unknown as Record<string, unknown>).toolCallId =
        innerToolCallId;
      return msg;
    })();

    const prepared = prepareReadyMessages(
      [parentAiCall, innerAi, innerToolResult],
      { ...defaultOptions, isNodeRunning: true },
    );

    const block = findSubagentBlock(prepared, parentToolCallId);
    expect(block).toBeDefined();
    expect(block!.type).toBe('subagent');
    expect(block!.status).toBe('calling');
    expect(block!.statistics?.usage?.totalTokens).toBe(250);
    expect(block!.statistics?.usage?.totalPrice).toBeCloseTo(0.01, 10);
  });

  it('1.6 — tool-only AI msg with multiple sibling tool_calls credits requestTokenUsage exactly once via reference dedup', () => {
    // Companion to 1.5: when an AI message has 2+ tool calls (still no chat
    // content), all sibling tool prepared items share the SAME
    // requestTokenUsage object by reference.  The WeakSet dedup must credit
    // only once — not N times.  The total price/tokens reported equal the
    // original AI message's usage, never multiplied by the tool count.
    const sharedUsage: ThreadMessageDto['requestTokenUsage'] = {
      inputTokens: 400,
      outputTokens: 100,
      totalTokens: 500,
      totalPrice: 0.02,
    };

    const toolItem1: PreparedMessage = {
      type: 'tool',
      id: 'tool-only-a',
      name: 'shell',
      status: 'executed',
      requestTokenUsage: sharedUsage,
      durationMs: 100,
    };

    const toolItem2: PreparedMessage = {
      type: 'tool',
      id: 'tool-only-b',
      name: 'files_read',
      status: 'executed',
      requestTokenUsage: sharedUsage,
      durationMs: 200,
    };

    const toolItem3: PreparedMessage = {
      type: 'tool',
      id: 'tool-only-c',
      name: 'shell',
      status: 'executed',
      requestTokenUsage: sharedUsage,
      durationMs: 300,
    };

    const stats = _accumulatePreparedStatistics([
      toolItem1,
      toolItem2,
      toolItem3,
    ]);

    expect(stats).toBeDefined();
    // Credited exactly once via reference dedup — not 3×.
    expect(stats!.usage!.totalPrice).toBeCloseTo(0.02, 10);
    expect(stats!.usage!.totalTokens).toBe(500);
  });
});

