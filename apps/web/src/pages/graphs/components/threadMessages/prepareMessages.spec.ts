/**
 * Minimal valid `ThreadMessageDto`.  Only the fields required by the
 * prepareReadyMessages processing paths are populated; everything else uses
 * safe default values.
 */
const makeMsg = (
  id: string,
  role: string,
  content: string,
  additionalKwargs: Record<string, unknown> = {},
  extra: Partial<
    Pick<
      ThreadMessageDto,
      'createdAt' | 'updatedAt' | 'nodeId' | 'externalThreadId'
    >
  > = {},
): ThreadMessageDto => ({
  id,
  threadId: 'thread-1',
  nodeId: 'node-1',
  externalThreadId: '',
  createdAt: '2024-01-01T00:00:00.000Z',
  updatedAt: '2024-01-01T00:00:00.000Z',
  ...extra,
  message: {
    id,
    role: role as string,
    content,
    additionalKwargs,
  } as ThreadMessageDto['message'],
});

